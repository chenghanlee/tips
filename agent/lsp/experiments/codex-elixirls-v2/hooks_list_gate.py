#!/usr/bin/env python3
"""E2 gate: which hooks Codex loads for a configured, TRUSTED Solution 2 worktree.

Usage: python3 hooks_list_gate.py /absolute/trusted/worktree /absolute/bundle
Uses Codex's read-only `hooks/list` (same method r24's verify-hooks used). Changes nothing.

PASS needs all of:
  1. the worktree's .codex/config.toml was generated by this bundle (names its bundle.py);
  2. no listed hook runs this bundle or `bundle.py hook`;
  3. no ENABLED hook comes from the mix-credo or mix-compile plugins;
  4. unrelated user hooks are still listed (the profile removed only its own);
  5. positive control: with `-c plugins.mix-credo@elixir-agent-tools.enabled=true` (unquoted:
     Codex splits the -c key on dots and keeps quotes, so a quoted key is silently ignored) the
     same listing shows an enabled mix-credo hook. Without that, check 3 is vacuous and
     the result is INCONCLUSIVE, not PASS.
"""

import json
import selectors
import subprocess
import sys
import time
from pathlib import Path

PLUGINS = ("mix-credo@elixir-agent-tools", "mix-compile@elixir-agent-tools")


def listed(workspace: Path, *flags: str) -> list[dict[str, object]]:
    server = subprocess.Popen(  # noqa: S603 - codex from PATH, fixed arguments, no shell
        ["codex", "app-server", "--stdio", *flags],  # noqa: S607
        cwd=workspace,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    )
    if server.stdin is None or server.stdout is None:
        raise RuntimeError("codex app-server pipes missing")
    selector = selectors.DefaultSelector()
    selector.register(server.stdout, selectors.EVENT_READ)
    deadline = time.monotonic() + 30

    def request(number: int, method: str, params: object) -> dict[str, object]:
        server.stdin.write(json.dumps({"id": number, "method": method, "params": params}) + "\n")
        server.stdin.flush()
        while selector.select(max(0.0, deadline - time.monotonic())):
            line = server.stdout.readline()
            if not line:
                break
            reply = json.loads(line)
            if reply.get("id") == number:
                if "result" not in reply:
                    raise RuntimeError(f"{method}: {reply.get('error')}")
                return reply["result"]
        raise RuntimeError(f"no answer to {method}")

    try:
        request(1, "initialize", {"clientInfo": {"name": "e2-hooks-gate", "version": "1"}})
        server.stdin.write('{"method": "initialized"}\n')
        server.stdin.flush()
        data = request(2, "hooks/list", {"cwds": [str(workspace)]})["data"]
    finally:
        server.stdin.close()
        try:
            server.wait(timeout=10)
        except subprocess.TimeoutExpired:
            server.kill()
            server.wait()
    return [hook for entry in data for hook in entry["hooks"]]


def plugin_enabled(hooks: list[dict[str, object]], plugin: str) -> bool:
    return any(h.get("pluginId") == plugin and h.get("enabled") for h in hooks)


def main() -> int:
    workspace, bundle = Path(sys.argv[1]).resolve(strict=True), Path(sys.argv[2]).resolve()
    config = (workspace / ".codex/config.toml").read_text()
    hooks = listed(workspace)
    control = listed(workspace, "-c", f"plugins.{PLUGINS[0]}.enabled=true")
    checks = {
        "config_from_bundle": str(bundle / "bundle.py") in config,
        "no_bundle_hook": not any(
            str(bundle) in str(h.get("command")) or "bundle.py hook" in str(h.get("command"))
            for h in hooks
        ),
        "no_enabled_credo_or_compile_hook": not any(plugin_enabled(hooks, p) for p in PLUGINS),
        "user_hooks_still_listed": any(h.get("source") == "user" for h in hooks),
        "positive_control_lists_credo": plugin_enabled(control, PLUGINS[0]),
    }
    verdict = (
        "PASS"
        if all(checks.values())
        else "INCONCLUSIVE"
        if all(v for k, v in checks.items() if k != "positive_control_lists_credo")
        else "FAIL"
    )
    summary = [
        {k: h.get(k) for k in ("eventName", "source", "pluginId", "enabled", "trustStatus")}
        for h in hooks
    ]
    version = subprocess.run(
        ["codex", "--version"],  # noqa: S607
        capture_output=True,
        text=True,
        check=False,
    ).stdout
    print(
        json.dumps(
            {"verdict": verdict, "codex": version.strip(), "checks": checks, "hooks": summary},
            indent=2,
        )
    )
    return 0 if verdict == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
